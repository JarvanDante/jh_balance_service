#!/bin/bash

# 生成protobuf文件并自动更新DAO以支持动态数据库路由

echo "=== 开始生成protobuf文件 ==="

# 生成protobuf文件
gf gen pb

echo "=== 开始清理omitempty标签 ==="

# 查找并清理所有生成的protobuf Go文件中的omitempty标签
find api -name "*.pb.go" | while read file; do
    if grep -q "omitempty" "$file"; then
        echo "清理文件: $file"
        sed -i '' 's/,omitempty//g' "$file"
    fi
done

echo "=== protobuf文件生成完成 ==="
echo

echo "=== 开始批量更新DAO文件以支持动态数据库路由 ==="

# 转换函数：snake_case 到 PascalCase
snake_to_pascal() {
    echo "$1" | awk -F_ '{
        result = ""
        for(i=1; i<=NF; i++) {
            result = result toupper(substr($i,1,1)) substr($i,2)
        }
        print result
    }'
}

# 转换函数：snake_case 到 camelCase  
snake_to_camel() {
    echo "$1" | awk -F_ '{
        result = $1
        for(i=2; i<=NF; i++) {
            result = result toupper(substr($i,1,1)) substr($i,2)
        }
        print result
    }'
}

# 提取自定义方法的函数
extract_custom_methods() {
    local file="$1"
    if [ -f "$file" ]; then
        # 查找 "Add your custom methods" 之后的所有内容
        awk '/Add your custom methods and functionality below\./{flag=1; next} flag' "$file"
    fi
}

# 检查是否需要额外的import
check_imports() {
    local custom_content="$1"
    local imports=""
    
    # 检查是否使用了fmt包
    if echo "$custom_content" | grep -q "fmt\."; then
        imports="$imports\n\t\"fmt\""
    fi
    
    echo -e "$imports"
}

# 查找所有DAO文件（排除internal目录和辅助文件）
find internal/dao -name "*.go" -not -path "*/internal/*" -not -name "dynamic_db_handler.go" -not -name "dao_helper.go" | while read file; do
    # 获取文件名（不含扩展名）
    filename=$(basename "$file" .go)
    
    echo "处理文件: $file"
    
    # 获取DAO类型名
    dao_type=$(snake_to_pascal "$filename")
    dao_var=$(snake_to_camel "$filename")
    
    echo "  DAO类型: $dao_type, DAO变量: $dao_var"
    
    # 提取现有的自定义方法
    custom_methods=""
    if [ -f "$file" ]; then
        custom_methods=$(extract_custom_methods "$file")
    fi
    
    # 检查需要的额外imports
    extra_imports=$(check_imports "$custom_methods")
    
    # 创建新的统一结构的DAO文件
    cat > "$file" << EOF
// =================================================================================
// This file is auto-generated by the GoFrame CLI tool. You may modify it as needed.
// =================================================================================

package dao

import (
	"context"$extra_imports
	"jh_balance_service/internal/dao/internal"
	
	"github.com/gogf/gf/v2/database/gdb"
)

// ${dao_var}Dao is the data access object for the table ${filename}.
// You can define custom methods on it to extend its functionality as needed.
type ${dao_var}Dao struct {
	*internal.${dao_type}Dao
}

var (
	// ${dao_type} is a globally accessible object for table ${filename} operations.
	${dao_type} = ${dao_var}Dao{internal.New${dao_type}Dao(DynamicDBHandler)}
)

// Ctx 重写Ctx方法，使用动态数据库连接
func (d ${dao_var}Dao) Ctx(ctx context.Context) *gdb.Model {
	// 使用辅助函数获取动态Model
	originalModel := d.${dao_type}Dao.Ctx(ctx)
	return GetDynamicModel(ctx, d.Table(), originalModel)
}

// Add your custom methods and functionality below.
$custom_methods
EOF
    
    echo "  已更新完成"
done

echo
echo "=== DAO文件更新完成 ==="
echo
echo "📝 更新说明："
echo "1. 所有DAO文件已统一为一致的结构"
echo "2. 都使用结构体嵌入和自定义Ctx方法"
echo "3. 保留了原有的自定义方法"
echo "4. 动态路由通过 GetDynamicModel 辅助函数实现"
echo
echo "🔧 使用方法："
echo "- 确保 Consul KV 中有站点配置: sites/{code}/base"
echo "- Gateway 会自动传递 site_id 到微服务"
echo "- DAO 会根据 site_id 自动切换到对应数据库"
echo
echo "✅ 现在可以运行脚本来统一所有DAO文件结构并保留自定义方法"