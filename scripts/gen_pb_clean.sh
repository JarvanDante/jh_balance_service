#!/bin/bash

# 生成protobuf文件并自动更新DAO以支持动态数据库路由

echo "=== 开始生成protobuf文件 ==="

# 生成protobuf文件（balance 相关用 gf，保留 dc 标签）
gf gen pb -p manifest/protobuf/frontend/balance/v1
gf gen pb -p manifest/protobuf/backend/balance/v1
gf gen pb -p manifest/protobuf/grpc/user/v1

# 生成 game 相关 pb（仅客户端，不生成 controller）
PROTO_DIR="manifest/protobuf"
OUT_DIR="api"
GAME_PROTO_FILES=(
    "grpc/game/backend/v1/game.proto"
    "grpc/game/frontend/v1/game.proto"
)

for proto in "${GAME_PROTO_FILES[@]}"; do
    /opt/homebrew/bin/protoc \
        --proto_path="${PROTO_DIR}" \
        --go_out=paths=source_relative:"${OUT_DIR}" \
        --go-grpc_out=paths=source_relative:"${OUT_DIR}" \
        "${PROTO_DIR}/${proto}"
done

echo "=== 开始清理omitempty标签和重复的dc标签 ==="

# 查找并清理所有生成的protobuf Go文件中的omitempty标签和重复的dc标签
find api -name "*.pb.go" | while read file; do
    if grep -q "omitempty" "$file" || grep -q 'dc:".*" dc:"' "$file"; then
        echo "清理文件: $file"
        # 移除 omitempty
        sed -i '' 's/,omitempty//g' "$file"
        # 清理重复的 dc: 标签，使用 Perl 正则表达式只保留第一个
        perl -i -pe 's/(dc:"[^"]*")(\s+dc:"[^"]*")+/$1/g' "$file"
    fi
done

echo "=== 格式化所有生成的 Go 文件 ==="

# 使用 gofmt 格式化所有生成的文件，确保格式一致
find api -name "*.pb.go" -exec gofmt -w {} \;

echo "=== protobuf文件生成完成 ==="
echo

echo "=== 开始批量更新DAO文件以支持动态数据库路由 ==="

# 转换函数：snake_case 到 PascalCase
snake_to_pascal() {
    echo "$1" | awk -F_ '{
        result = ""
        for(i=1; i<=NF; i++) {
            result = result toupper(substr($i,1,1)) substr($i,2)
        }
        print result
    }'
}

# 转换函数：snake_case 到 camelCase
snake_to_camel() {
    echo "$1" | awk -F_ '{
        result = $1
        for(i=2; i<=NF; i++) {
            result = result toupper(substr($i,1,1)) substr($i,2)
        }
        print result
    }'
}

# 提取自定义方法的函数（改进版：跳过标记注释本身）
extract_custom_methods() {
    local file="$1"
    if [ -f "$file" ]; then
        # 查找 "Add your custom methods" 之后的所有内容
        # 使用 flag=1; next 跳过标记行本身，避免重复添加
        awk '/Add your custom methods and functionality below\./{flag=1; next} flag' "$file" | \
        # 过滤掉可能残留的重复标记注释
        grep -v "^// Add your custom methods and functionality below\."
    fi
}

# 提取现有的 import 部分（保留用户自定义的 import）
extract_imports() {
    local file="$1"
    if [ -f "$file" ]; then
        # 提取 import ( 到 ) 之间的内容，保持原有格式
        awk '
        /^import \($/,/^\)$/ {
            if ($0 !~ /^import \(/ && $0 !~ /^\)$/) {
                print
            }
        }
        ' "$file"
    fi
}

# 检查是否需要额外的import（已废弃，改用 extract_imports）
check_imports() {
    local custom_content="$1"
    local imports=""
    
    # 检查是否使用了fmt包
    if echo "$custom_content" | grep -q "fmt\."; then
        imports="$imports
    \"fmt\""
    fi
    
    # 检查是否使用了entity
    if echo "$custom_content" | grep -q "\*entity\." || echo "$custom_content" | grep -q "entity\."; then
        imports="$imports
    \"jh_balance_service/internal/model/entity\""
    fi
    
    # 检查是否使用了g.Map或g.Redis等
    if echo "$custom_content" | grep -q "g\."; then
        imports="$imports
    \"github.com/gogf/gf/v2/frame/g\""
    fi
    
    # 检查是否使用了gtime
    if echo "$custom_content" | grep -q "gtime\."; then
        imports="$imports
    \"github.com/gogf/gf/v2/os/gtime\""
    fi
    
    # 检查是否使用了balanceConsts
    if echo "$custom_content" | grep -q "balanceConsts\."; then
        imports="$imports
    balanceConsts \"jh_balance_service/internal/consts/backend/balance\""
    fi
    
    printf "%s" "$imports"
}

# 查找所有DAO文件（排除internal目录和辅助文件）
find internal/dao -name "*.go" -not -path "*/internal/*" -not -name "dynamic_db_handler.go" -not -name "dao_helper.go" | while read file; do
    # 获取文件名（不含扩展名）
    filename=$(basename "$file" .go)
    
    echo "处理文件: $file"
    
    # 获取DAO类型名
    dao_type=$(snake_to_pascal "$filename")
    dao_var=$(snake_to_camel "$filename")
    
    echo "  DAO类型: $dao_type, DAO变量: $dao_var"
    
    # 提取现有的自定义方法
    custom_methods=""
    if [ -f "$file" ]; then
        custom_methods=$(extract_custom_methods "$file")
    fi
    
    # 提取现有的 imports（保留用户自定义的）
    existing_imports=""
    if [ -f "$file" ]; then
        existing_imports=$(extract_imports "$file")
    fi
    
    # 如果没有提取到 imports，使用默认的
    if [ -z "$existing_imports" ]; then
        existing_imports="    \"context\"
    \"jh_balance_service/internal/dao/internal\"
    
    \"github.com/gogf/gf/v2/database/gdb\""
    fi
    
    # 创建新的统一结构的DAO文件
    {
        echo "// ================================================================================="
        echo "// This file is auto-generated by the GoFrame CLI tool. You may modify it as needed."
        echo "// ================================================================================="
        echo ""
        echo "package dao"
        echo ""
        echo "import ("
        echo "$existing_imports"
        echo ")"
        echo ""
        echo "// ${dao_var}Dao is the data access object for the table ${filename}."
        echo "// You can define custom methods on it to extend its functionality as needed."
        echo "type ${dao_var}Dao struct {"
        echo "    *internal.${dao_type}Dao"
        echo "}"
        echo ""
        echo "var ("
        echo "    // ${dao_type} is a globally accessible object for table ${filename} operations."
        echo "    ${dao_type} = ${dao_var}Dao{internal.New${dao_type}Dao(DynamicDBHandler)}"
        echo ")"
        echo ""
        echo "// Ctx 重写Ctx方法，使用动态数据库连接"
        echo "func (d ${dao_var}Dao) Ctx(ctx context.Context) *gdb.Model {"
        echo "    // 使用辅助函数获取动态Model"
        echo "    originalModel := d.${dao_type}Dao.Ctx(ctx)"
        echo "    return GetDynamicModel(ctx, d.Table(), originalModel)"
        echo "}"
        echo ""
        echo "// Add your custom methods and functionality below."
        if [ -n "$custom_methods" ]; then
            echo "$custom_methods"
        fi
    } > "$file"
    
    echo "  已更新完成"
done

echo
echo "=== 格式化所有 DAO 文件 ==="

# 使用 gofmt 格式化所有 DAO 文件，确保格式一致
find internal/dao -name "*.go" -not -path "*/internal/*" -exec gofmt -w {} \;

echo "=== DAO文件更新完成 ==="
echo
echo "📝 更新说明："
echo "1. 所有DAO文件已统一为一致的结构"
echo "2. 都使用结构体嵌入和自定义Ctx方法"
echo "3. 保留了原有的自定义方法"
echo "4. 动态路由通过 GetDynamicModel 辅助函数实现"
echo
echo "🔧 使用方法："
echo "- 确保 Consul KV 中有站点配置: sites/{code}/base"
echo "- Gateway 会自动传递 site_id 到微服务"
echo "- DAO 会根据 site_id 自动切换到对应数据库"
echo
echo "✅ 现在可以运行脚本来统一所有DAO文件结构并保留自定义方法"
echo

echo "=== 清理不需要的文件 ==="

# 定义需要删除的目录列表
DIRS_TO_DELETE=(
    "internal/controller/balance"
    "internal/controller/game"
    "internal/controller/user"
    # 如果有其他需要删除的目录，在这里添加
    # "internal/controller/other_dir"
)

# 批量删除不需要的目录
deleted_count=0
for dir in "${DIRS_TO_DELETE[@]}"; do
    if [ -d "$dir" ]; then
        echo "删除不需要的目录: $dir"
        rm -rf "$dir"
        deleted_count=$((deleted_count + 1))
    fi
done

if [ $deleted_count -gt 0 ]; then
    echo "✅ 清理完成，共删除 $deleted_count 个目录"
else
    echo "目录不存在，无需清理"
fi
